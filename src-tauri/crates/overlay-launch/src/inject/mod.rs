/// The name of the hook's init export. The stub resolves it with `GetProcAddress`.
#[cfg(any(target_arch = "x86", target_arch = "x86_64"))]
const INIT_NAME: &[u8] = b"GobboOverlayInit\0";
/// The search path of the hook and its dependencies: its own folder and `System32`, never the game folder.
#[cfg(any(target_arch = "x86", target_arch = "x86_64"))]
const HOOK_SEARCH: u32 = LOAD_LIBRARY_SEARCH_DLL_LOAD_DIR | LOAD_LIBRARY_SEARCH_SYSTEM32;

/// Loads `hook` into `process` by pointing its suspended `thread` at a stub. The caller resumes the thread.
///
/// # Safety
/// `process` must be a process handle with the rights `CreateProcessW` returns, and `thread` must be its suspended
/// main thread.
pub unsafe fn inject_early(process: HANDLE, thread: HANDLE, hook: &Path) -> io::Result<()> {
    if !hook.is_file() {
        return Err(io::Error::new(
            io::ErrorKind::NotFound,
            format!("the overlay hook {} is missing", hook.display()),
        ));
    }
    let hook_path = wide(hook.as_os_str());

    #[cfg(target_arch = "x86_64")]
    {
        let kernel = kernel32()?;
        let data = Data64 {
            load_library_ex_w: address(kernel, c"LoadLibraryExW")? as u64,
            get_proc_address: address(kernel, c"GetProcAddress")? as u64,
            exit_process: address(kernel, c"ExitProcess")? as u64,
            hook_path,
            init_name: INIT_NAME,
            flags: HOOK_SEARCH,
        };
        unsafe { inject_x64(process, thread, data) }
    }
    #[cfg(target_arch = "x86")]
    {
        let kernel = kernel32()?;
        let data = Data32 {
            load_library_ex_w: address(kernel, c"LoadLibraryExW")? as u32,
            get_proc_address: address(kernel, c"GetProcAddress")? as u32,
            exit_process: address(kernel, c"ExitProcess")? as u32,
            hook_path,
            init_name: INIT_NAME,
            flags: HOOK_SEARCH,
        };
        unsafe { inject_x86(process, thread, data) }
    }
    #[cfg(not(any(target_arch = "x86_64", target_arch = "x86")))]
    {
        let _ = (process, thread, hook_path);
        Err(io::Error::other(
            "early overlay injection is not implemented on this architecture",
        ))
    }
}

/// Loads `hook` into the suspended thread `tid` of process `pid`. Used by the 32-bit helper, which runs in another
/// process and cannot use the handles of the 64-bit launcher.
pub fn inject_early_by_tid(pid: u32, tid: u32, hook: &Path) -> io::Result<()> {
    // SAFETY: the rights are the ones the write and the context change need; the process id is the caller's target.
    let process = unsafe {
        OpenProcess(
            PROCESS_QUERY_INFORMATION | PROCESS_VM_OPERATION | PROCESS_VM_READ | PROCESS_VM_WRITE,
            FALSE,
            pid,
        )
    };
    if process.is_null() {
        return Err(io::Error::last_os_error());
    }
    // SAFETY: the rights are the ones the context read and write need; the thread id is the caller's target.
    let thread = unsafe { OpenThread(THREAD_GET_CONTEXT | THREAD_SET_CONTEXT, FALSE, tid) };
    if thread.is_null() {
        // SAFETY: `process` was opened above and is closed once.
        unsafe { CloseHandle(process) };
        return Err(io::Error::last_os_error());
    }
    // SAFETY: both handles were opened above with the rights the injection needs.
    let result = unsafe { inject_early(process, thread, hook) };
    // SAFETY: each handle was opened above and is closed once.
    unsafe {
        CloseHandle(thread);
        CloseHandle(process);
    }
    result
}

/// The `kernel32` module. It is loaded in the launcher; the addresses of its exports are valid in the target because
/// Windows maps it at the same base in every process on the machine.
#[cfg(any(target_arch = "x86", target_arch = "x86_64"))]
fn kernel32() -> io::Result<HMODULE> {
    let name = wide(std::ffi::OsStr::new("kernel32.dll"));
    // SAFETY: `name` is a NUL-terminated UTF-16 path.
    let module = unsafe { GetModuleHandleW(name.as_ptr()) };
    if !module.is_null() {
        return Ok(module);
    }
    // SAFETY: `name` is a NUL-terminated UTF-16 path and the call only loads a system DLL.
    let module = unsafe { LoadLibraryW(name.as_ptr()) };
    if module.is_null() {
        return Err(io::Error::last_os_error());
    }
    Ok(module)
}

/// The address of an export of `module`, or an error naming it.
#[cfg(any(target_arch = "x86", target_arch = "x86_64"))]
fn address(module: HMODULE, name: &CStr) -> io::Result<usize> {
    // SAFETY: `module` is a loaded module and `name` is a NUL-terminated export name.
    let found = unsafe { GetProcAddress(module, name.as_ptr().cast()) };
    found
        .map(|function| function as usize)
        .ok_or_else(|| io::Error::other(format!("no {} in kernel32", name.to_string_lossy())))
}

/// Replaces the context of the suspended thread with the stub, after writing the stub into the process.
#[cfg(any(target_arch = "x86", target_arch = "x86_64"))]
unsafe fn place(process: HANDLE, remote: *mut c_void, image: &Image) -> io::Result<()> {
    let mut written = 0;
    // SAFETY: `remote` is an allocation of `image.len()` bytes in `process`.
    let code = unsafe {
        WriteProcessMemory(
            process,
            remote,
            image.code.as_ptr().cast(),
            image.code.len(),
            &mut written,
        )
    };
    if code == FALSE || written != image.code.len() {
        return Err(io::Error::last_os_error());
    }
    // SAFETY: the data block follows the code in the same allocation.
    let data = unsafe { remote.cast::<u8>().add(image.code.len()) };
    let mut data_written = 0;
    // SAFETY: `data` is the rest of the allocation, and `image.data` has that length.
    let result = unsafe {
        WriteProcessMemory(
            process,
            data.cast(),
            image.data.as_ptr().cast(),
            image.data.len(),
            &mut data_written,
        )
    };
    if result == FALSE || data_written != image.data.len() {
        return Err(io::Error::last_os_error());
    }
    // SAFETY: the code was just written; this only makes the instruction cache see it.
    unsafe { FlushInstructionCache(process, remote, image.len()) };
    // The stub only reads its data, so the whole image can be read and executed. A failure leaves it writable, which
    // is still executable; it is a hardening step, not a correctness one.
    let mut old = 0;
    // SAFETY: the allocation and its length are the ones made above.
    unsafe { VirtualProtectEx(process, remote, image.len(), PAGE_EXECUTE_READ, &mut old) };
    Ok(())
}

/// Allocates the image, points its internal addresses at the allocation, and writes it.
#[cfg(any(target_arch = "x86", target_arch = "x86_64"))]
unsafe fn write_image(process: HANDLE, mut image: Image) -> io::Result<*mut c_void> {
    // SAFETY: the allocation is in the target process and is owned by this function until it is returned or freed.
    let remote = unsafe {
        VirtualAllocEx(
            process,
            null(),
            image.len(),
            MEM_COMMIT | MEM_RESERVE,
            PAGE_EXECUTE_READWRITE,
        )
    };
    if remote.is_null() {
        return Err(io::Error::last_os_error());
    }
    let data_base = remote as usize + image.code.len();
    if let Err(error) = image
        .set_data_base(data_base)
        .and_then(|()| image.set_string_pointers(data_base))
    {
        // SAFETY: the allocation was made above and is not used after this failure.
        unsafe { VirtualFreeEx(process, remote, 0, MEM_RELEASE) };
        return Err(io::Error::other(error.to_string()));
    }
    // SAFETY: the image and the allocation were built for each other.
    if let Err(error) = unsafe { place(process, remote, &image) } {
        // SAFETY: the allocation was made above and is not used after this failure.
        unsafe { VirtualFreeEx(process, remote, 0, MEM_RELEASE) };
        return Err(error);
    }
    Ok(remote)
}

#[cfg(target_arch = "x86_64")]
/// Injects the x64 stub into the suspended x64 thread.
unsafe fn inject_x64(process: HANDLE, thread: HANDLE, data: Data64) -> io::Result<()> {
    let mut context = CONTEXT {
        ContextFlags: CONTEXT_CONTROL_AMD64,
        ..Default::default()
    };
    // The documented prerequisite for reading the extended state on current Windows. A failure is not fatal for the
    // control registers this needs.
    let _ = unsafe { SetXStateFeaturesMask(&mut context, 0) };
    // SAFETY: `thread` is the suspended thread the caller owns, and `context` is a valid CONTEXT.
    if unsafe { GetThreadContext(thread, &mut context) } == FALSE {
        return Err(io::Error::last_os_error());
    }
    let original = context.Rip;
    let image = stub::build64(&data, original).map_err(stub_error)?;
    // SAFETY: the allocation and the image are built for the target process.
    let remote = unsafe { write_image(process, image)? };
    context.Rip = remote as u64;
    // SAFETY: `thread` is the suspended thread, and `context` is the context read above with the new instruction.
    if unsafe { SetThreadContext(thread, &context) } == FALSE {
        // SAFETY: the allocation is not used if the context cannot be set.
        unsafe { VirtualFreeEx(process, remote, 0, MEM_RELEASE) };
        return Err(io::Error::last_os_error());
    }
    Ok(())
}

#[cfg(target_arch = "x86")]
/// Injects the x86 stub into the suspended x86 thread.
unsafe fn inject_x86(process: HANDLE, thread: HANDLE, data: Data32) -> io::Result<()> {
    let mut context = CONTEXT {
        ContextFlags: CONTEXT_CONTROL_X86,
        ..Default::default()
    };
    // SAFETY: `thread` is the suspended thread the caller owns, and `context` is a valid CONTEXT.
    if unsafe { GetThreadContext(thread, &mut context) } == FALSE {
        return Err(io::Error::last_os_error());
    }
    let original = context.Eip;
    let image = stub::build32(&data, original).map_err(stub_error)?;
    // SAFETY: the allocation and the image are built for the target process.
    let remote = unsafe { write_image(process, image)? };
    context.Eip = remote as u32;
    // SAFETY: `thread` is the suspended thread, and `context` is the context read above with the new instruction.
    if unsafe { SetThreadContext(thread, &context) } == FALSE {
        // SAFETY: the allocation is not used if the context cannot be set.
        unsafe { VirtualFreeEx(process, remote, 0, MEM_RELEASE) };
        return Err(io::Error::last_os_error());
    }
    Ok(())
}

/// The stub builder's error as an `io::Error`.
#[cfg(any(target_arch = "x86", target_arch = "x86_64"))]
fn stub_error(error: StubError) -> io::Error {
    io::Error::other(error.to_string())
}
