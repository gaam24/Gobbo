//! Loads the overlay hook into a suspended program before its loader initializes the process.
//!
//! `CreateProcessW(CREATE_SUSPENDED)` leaves the program before `LdrInitializeThunk`. This module writes a small stub
//! into the program, points the program's main thread at it, and lets the launcher resume the thread. The stub loads
//! the hook with `LoadLibraryExW`, calls `GobboOverlayInit`, and returns to the instruction the loader was going to run.
//! The loader then resolves the program's own static imports, which the launcher has pointed at the mod layer. The
//! rest of the import tree is resolved by that first `LoadLibraryExW`, before the hook is active: see the known gap in
//! `crates/overlay-hook/ARCHITECTURE.md`, invariant 11.
//!
//! The x86 and x64 stubs are generated by `stub`. A 64-bit process cannot set the context of a 32-bit thread, so a
//! 64-bit launcher asks `gobbo_overlay_inject32.exe` to do it. The helper only sets the context; the caller resumes the
//! thread and waits for the hook's readiness event.

