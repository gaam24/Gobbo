import { strict as assert } from "node:assert";
import path from "node:path";
import type { Status_Serialize as Status } from "../../src/bindings";
import { invoke, reloadWindow, waitForShell } from "../support/bridge";
import { dataDir, definitionsDir } from "../support/env";
import { exists, expectNoFile, expectText, removeTree, writeFile } from "../support/files";
import { modZip } from "../support/fixtures";
import { apply, cleanupGame, enableMods, importMods, seedGame, statusOf, uniqueId, waitForStage } from "../support/seed";
import { clickByLabel, clickByText, count, setThrow, waitForHeading, waitForNoText, waitForText } from "../support/ui";

describe("recovery", () => {
	it("keeps a page failure inside its screen, logs it and retries without a reload", async () => {
		const id = uniqueId("recover-page");
		const name = `E2E Recover ${id}`;
		const { fixture } = await seedGame({ id, name });
		await setThrow("mods");
		await clickByLabel("Downloads");
		await waitForHeading("Downloads");
		await clickByLabel(name);
		await waitForText("Something went wrong");
		await waitForText("E2E forced render failure in mods");
		await waitForText("Reload window");
		assert.ok((await count("nav")) > 0, "the rail disappeared with one page");
		await setThrow(null);
		await clickByText("Try again", "button", "[role='alert']");
		await waitForHeading(name);
		await waitForNoText("Something went wrong");
		await cleanupGame(id);
		removeTree(path.join(definitionsDir, id));
		removeTree(fixture.root);
	});
	it("shows the whole-window fallback when the shell itself fails and recovers on reload", async () => {
		await setThrow("shell");
		await reloadWindow();
		await waitForText("Something went wrong");
		await waitForText("Reload window");
		assert.equal(await count("nav"), 0, "the shell fallback kept the rail");
		await setThrow(null);
		await clickByText("Reload window", "button", "[role='alert']");
		await waitForShell();
		assert.ok((await count("nav [aria-label]")) > 0, "the rail did not come back after the reload");
		await waitForNoText("Something went wrong");
	});
	it("keeps a game usable after its settings and profiles files are damaged", async () => {
		const id = uniqueId("recover-broken");
		const name = `E2E Broken ${id}`;
		const { fixture } = await seedGame({ id, name });
		const gameDir = path.join(dataDir, "games", id);
		writeFile(path.join(gameDir, "config.json"), "{ not json");
		writeFile(path.join(gameDir, "profiles.json"), "[]");
		await reloadWindow();
		await waitForShell();
		const status: Status = await statusOf(id);
		assert.equal(status.settings.game_root, "", "the broken settings were not replaced by defaults");
		assert.equal(status.profiles.length, 1, "the broken profiles file did not start a default profile");
		assert.ok(exists(path.join(gameDir, "config.json.broken")), "the broken settings file was not kept");
		assert.ok(exists(path.join(gameDir, "profiles.json.broken")), "the broken profiles file was not kept");
		await waitForText("Set the game folder");
		await cleanupGame(id);
		removeTree(path.join(definitionsDir, id));
		removeTree(fixture.root);
	});
	it("undoes an interrupted apply and cleans its journal", async () => {
		const id = uniqueId("recover-interrupted");
		const name = `E2E Interrupted ${id}`;
		const { fixture } = await seedGame({ id, name });
		await importMods(id, [modZip(`recover-${id}.zip`, `Recover ${id}`)]);
		await enableMods(id);
		const before = await statusOf(id);
		const mod = before.mods[0];
		const active = before.profiles.find((profile) => profile.active);
		assert.ok(mod);
		assert.ok(active);
		await apply(id);
		const state = path.join(dataDir, "games", id, "state", active.id);
		const staged = path.join(state, "mods", "Mods", `mod${mod.folder}`, "content/x.ws");
		expectText(staged, "x");
		const gameFile = path.join(fixture.root, "Mods", `mod${mod.folder}`, "content/x.ws");
		expectNoFile(gameFile);
		removeTree(path.join(state, "deployment.json"));
		assert.ok(exists(path.join(state, "journal.jsonl")), "the journal is missing after the apply");
		await invoke("undo", { game: id });
		expectNoFile(gameFile);
		await waitForStage(id, "ready");
		assert.ok(!exists(path.join(state, "journal.jsonl")), "the undo left the journal behind");
		await cleanupGame(id);
		removeTree(path.join(definitionsDir, id));
		removeTree(fixture.root);
	});
	it("starts over when the game folder moved away", async () => {
		const id = uniqueId("recover-folder");
		const name = `E2E Folder ${id}`;
		const { fixture } = await seedGame({ id, name });
		removeTree(fixture.root);
		await reloadWindow();
		const status = await statusOf(id);
		assert.equal(status.game_ready, false, "the missing game folder still counts as ready");
		await waitForText("Set the game folder");
		await cleanupGame(id);
		removeTree(path.join(definitionsDir, id));
	});
});
